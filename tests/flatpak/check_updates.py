"""Check stock GNOME Software against a disposable local Flatpak repository."""

import os
import gzip
from pathlib import Path
import re
import subprocess
import tempfile
import time


PLATFORM = "org.mertensia.TestPlatform"
APPLICATIONS = {"Unchanged": "shared=network;\n", "Reduced": "shared=network;\nfilesystems=home:ro;\n",
                "Expanded": "shared=network;\n"}


def run(argv, timeout=120):
    # GTK/GIO helpers can outlive a command and inherit its output. A file keeps
    # those helpers from holding an output pipe open after the command exits.
    with tempfile.TemporaryFile(mode="w+") as log:
        result = subprocess.run(argv, text=True, stdout=log, stderr=log, timeout=timeout)
        log.seek(0)
        output = log.read()
    if result.returncode:
        raise RuntimeError(f"{argv}: {output[-4000:]}")
    return output


def export(repository, root, name, permissions, version):
    directory = root / (name + "-" + version)
    files = directory / "files"
    files.mkdir(parents=True)
    if name == PLATFORM:
        metadata = f"[Runtime]\nname={name}\nruntime={name}/x86_64/1\nsdk={name}/x86_64/1\n"
    else:
        metadata = f"[Application]\nname={name}\nruntime={PLATFORM}/x86_64/1\nsdk={PLATFORM}/x86_64/1\ncommand=test-app\n[Context]\n{permissions}"
        binary = files / "bin/test-app"
        binary.parent.mkdir()
        binary.write_text("#!/bin/sh\nexit 0\n")
        binary.chmod(0o755)
        desktop = files / f"share/applications/{name}.desktop"
        desktop.parent.mkdir(parents=True)
        desktop.write_text(f"[Desktop Entry]\nType=Application\nName={name}\nExec=test-app\nIcon=application-x-executable\n")
        metainfo = files / f"share/metainfo/{name}.metainfo.xml"
        metainfo.parent.mkdir(parents=True)
        metainfo.write_text(f'''<?xml version="1.0" encoding="UTF-8"?>
<component type="desktop-application"><id>{name}</id><name>{name}</name>
<summary>Disposable automatic update fixture</summary>
<metadata_license>CC0-1.0</metadata_license><project_license>MIT</project_license>
<description><p>Tests automatic application update permissions.</p></description>
<launchable type="desktop-id">{name}.desktop</launchable>
<releases><release version="{version}" date="2026-10-23"/></releases></component>
''')
        # Normally generated by flatpak-builder/appstream-compose. Keep these
        # tiny fixtures independent of an SDK and its network downloads.
        catalog = files / f"share/app-info/xmls/{name}.xml.gz"
        catalog.parent.mkdir(parents=True)
        component = metainfo.read_text().split("?>", 1)[1].strip()
        component = component.replace("</component>",
                                      f'<bundle type="flatpak">app/{name}/x86_64/1</bundle>'
                                      '<icon type="stock">application-x-executable</icon></component>')
        with gzip.open(catalog, "wt") as stream:
            stream.write('<components version="0.8">' + component + '</components>')
    (directory / "metadata").write_text(metadata)
    if name != PLATFORM:
        run(["flatpak", "build-finish", str(directory)])
    args = ["flatpak", "build-export", "--disable-sandbox", "--arch=x86_64", "--files=files"]
    if name == PLATFORM:
        args.append("--runtime")
    run([*args, str(repository), str(directory), "1"])


def commit(scope, name):
    return run(["flatpak", "info", scope, "--show-commit", "org.mertensia.Test" + name]).strip()


def check_transactions(before):
    # Exercise the native Flatpak cancellation path. The GNOME session's
    # background scheduler and visual permission review are interactive tests.
    for scope in ("--system", "--user"):
        result = subprocess.run(["flatpak", "update", scope, "org.mertensia.TestExpanded"],
                                input="n\n", text=True, capture_output=True, timeout=30)
        if (result.returncode == 0 or not re.search(r"Proceed with these changes.*\[Y/n\]: n", result.stdout + result.stderr)
                or commit(scope, "Expanded") != before[scope, "Expanded"]):
            raise AssertionError("Declining the permission-expanding update did not preserve the installed app: "
                                 + result.stdout + result.stderr)
        run(["flatpak", "update", scope, "--noninteractive", "org.mertensia.TestUnchanged", "org.mertensia.TestReduced"])
        for name in ("Unchanged", "Reduced"):
            if commit(scope, name) == before[scope, name]:
                raise AssertionError("Unrelated update did not apply: " + name)
        if commit(scope, "Expanded") != before[scope, "Expanded"]:
            raise AssertionError("Unrelated updates installed the held permission-expanding app")
    print("Flatpak cancellation preserved expanded-access apps; unchanged/reduced updates applied in both scopes", flush=True)


def main():
    if not Path("/usr/share/mertensia-flatpak-tests/check_updates.py").exists() or Path("/run/ostree-booted").exists():
        raise RuntimeError("run these checks only in the disposable test container")
    with tempfile.TemporaryDirectory(prefix="mertensia-flatpak-") as temporary:
        root = Path(temporary)
        home = root / "home"
        home.mkdir()
        os.environ.update(HOME=str(home), XDG_DATA_HOME=str(home / ".local/share"),
                          XDG_CACHE_HOME=str(home / ".cache"), XDG_CONFIG_HOME=str(home / ".config"),
                          DISPLAY=":88", GSETTINGS_BACKEND="keyfile", GIO_USE_NETWORK_MONITOR="base",
                          LC_ALL="C.UTF-8",
                          GNOME_SOFTWARE_PLUGINS_ALLOWLIST="flatpak,appstream,generic-updates,os-release")
        Path("/run/dbus").mkdir(exist_ok=True)
        run(["dbus-daemon", "--system", "--fork", "--nopidfile"])
        display = subprocess.Popen(["Xvfb", ":88", "-screen", "0", "1280x1024x24", "-nolisten", "tcp"])
        try:
            deadline = time.monotonic() + 10
            while not Path("/tmp/.X11-unix/X88").exists():
                if display.poll() is not None or time.monotonic() > deadline:
                    raise RuntimeError("test display did not start")
                time.sleep(0.1)
            # This is a local fixture test; do not refresh the online review
            # service alongside application metadata.
            run(["gsettings", "set", "org.gnome.software", "review-server", "''"])
            repository = root / "repository"
            export(repository, root, PLATFORM, "", "1")
            for name, permissions in APPLICATIONS.items():
                export(repository, root, "org.mertensia.Test" + name, permissions, "1")
            run(["flatpak", "build-update-repo", "--generate-static-deltas", str(repository)])
            for scope in ("--system", "--user"):
                run(["flatpak", "remote-add", scope, "--no-gpg-verify", "fixtures", repository.as_uri()])
                run(["flatpak", "install", scope, "--noninteractive", "fixtures", PLATFORM])
                for name in APPLICATIONS:
                    run(["flatpak", "install", scope, "--noninteractive", "fixtures", "org.mertensia.Test" + name])
            print("Local Flatpak fixtures installed in both scopes", flush=True)
            before = {(scope, name): commit(scope, name) for scope in ("--system", "--user") for name in APPLICATIONS}
            for name in APPLICATIONS:
                permissions = "shared=network;\n"
                if name == "Expanded":
                    permissions += "filesystems=home;\n"
                export(repository, root, "org.mertensia.Test" + name, permissions, "2")
            run(["flatpak", "build-update-repo", str(repository)])
            cmd = ["/usr/libexec/gnome-software-cmd", "--plugin-allowlist=flatpak,appstream"]
            run([*cmd, "refresh", "--cache-age=0"])
            output = run([*cmd, "updates", "--show-results", "--refine-flags=permissions"])
            for scope in ("system", "user"):
                for name in APPLICATIONS:
                    identity = f"{scope}/flatpak/fixtures/org.mertensia.Test{name}/1"
                    matches = [block for block in output.split("GsApp:")
                               if re.search(r"^unique-id:\s+" + re.escape(identity) + r"$", block, re.MULTILINE)]
                    if len(matches) != 1 or ("new-permissions" in matches[0]) != (name == "Expanded"):
                        raise AssertionError("Incorrect native permission classification for " + identity + "\n" + output)
            print("Native permission classification passed for unchanged/reduced/expanded access in both scopes", flush=True)
            check_transactions(before)
        finally:
            display.terminate()
            display.wait(timeout=10)


if __name__ == "__main__":
    main()
